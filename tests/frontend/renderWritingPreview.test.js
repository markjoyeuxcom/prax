import test from 'node:test';
import assert from 'node:assert/strict';
import { renderWritingPreviewHtml } from '../../public/js/renderWritingPreview.js';

const ctx = { action: 'rewrite', label: 'Rewrite for clarity', verb: 'Replace document', mode: 'whole', docId: 'd1', model: 'm' };

test('the preview is a modal dialog with a Cancel/Close button in every state', () => {
  const loading = renderWritingPreviewHtml({ writeContext: ctx, writeLoading: true });
  assert.match(loading, /role="dialog" aria-modal="true"[^>]*aria-busy="true"/);
  assert.match(loading, /data-action="close-write">Cancel</);
  const failed = renderWritingPreviewHtml({ writeContext: ctx, writeError: 'The model could not complete this. Try again.' });
  assert.match(failed, /role="alert"/);
  assert.match(failed, /data-action="close-write">Close</);
  assert.match(failed, /data-action="retry-write">Try again</);
  assert.doesNotMatch(failed, /apply-write/);
  const noModel = renderWritingPreviewHtml({ writeContext: ctx, writeError: 'No AI model configured — set one in Settings ▸ Intelligence.' });
  assert.match(noModel, /data-action="open-ai-settings"/);
});

test('a result says applying saves like typing with Undo, and warns when the document is verified', () => {
  const html = renderWritingPreviewHtml({ writeContext: { ...ctx, verified: true }, writeResult: 'text' }, { resultHtml: '<p>text</p>' });
  assert.match(html, /Generated by m\. Nothing changes until you apply; applying saves like typing, and Undo restores the previous text\./);
  assert.match(html, /This document is verified; applying keeps the mark/);
  assert.match(html, /data-action="apply-write">Replace document</);
  assert.doesNotMatch(renderWritingPreviewHtml({ writeContext: ctx, writeResult: 'text' }), /is verified/);
});
