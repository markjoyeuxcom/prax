// Bundle the skill scripts (skills/src/*.mjs + cli/lib) into single dependency-
// free files under skills/<name>/scripts/. The bundles are COMMITTED so the
// skill pack installs from the repository without a build step or checkout.
// `--check` fails when a committed bundle is stale (wired into `npm run check`).
import { build } from 'esbuild';
import { chmodSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const SKILLS = [
  { entry: 'skills/src/recall.mjs', out: 'skills/prax-recall/scripts/recall.mjs' },
  { entry: 'skills/src/remember.mjs', out: 'skills/prax-remember/scripts/remember.mjs' },
];
const BANNER = '#!/usr/bin/env node\n'
  + '// GENERATED by scripts/build-skills.mjs from skills/src + cli/lib — do not edit.\n'
  + '// Rebuild with `npm run skills:build`. Needs Node 20+; no packages, no repo checkout.\n';

const check = process.argv.includes('--check');
let stale = 0;
for (const skill of SKILLS) {
  const result = await build({
    entryPoints: [skill.entry],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    write: false,
    banner: { js: BANNER },
    legalComments: 'none',
    logLevel: 'silent',
  });
  const code = result.outputFiles[0].text;
  if (check) {
    let current = '';
    try { current = readFileSync(skill.out, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== code) {
      stale += 1;
      console.error(`stale: ${skill.out} does not match its sources — run npm run skills:build`);
    }
  } else {
    mkdirSync(dirname(skill.out), { recursive: true });
    writeFileSync(skill.out, code);
    chmodSync(skill.out, 0o755);
    console.log(`built ${skill.out} (${code.length} bytes)`);
  }
}
if (check && stale === 0) console.log('skill bundles are up to date');
process.exit(stale ? 1 : 0);
