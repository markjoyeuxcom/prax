// `prax mirror --agents-block`: compile a project's VERIFIED standing rules —
// decisions, plus any document tagged `convention` — into a managed block of a
// workspace instruction file (AGENTS.md / CLAUDE.md), so every agent session
// starts with them. Unverified knowledge is never compiled; it stays with
// recall, where it is labelled. The block is bounded, deterministic (no
// timestamps) and edited with the installer's managed-marker routine.
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { parseMirrorMarkdown, recoverBody } from './mirrorFormat.js';

export const AGENTS_BLOCK_MARKER = 'prax-library';
export const DEFAULT_BLOCK_TYPES = ['decision'];
export const DEFAULT_BLOCK_TAGS = ['convention'];
export const DEFAULT_BLOCK_MAX_CHARS = 8000;
export const MIN_BLOCK_MAX_CHARS = 1000;
export const DOCUMENT_BODY_MAX_CHARS = 1500;

// Which export documents the block compiles: active, verified, and of a
// selected type or carrying a selected tag.
export function selectBlockDocuments(documents, { types = DEFAULT_BLOCK_TYPES, tags = DEFAULT_BLOCK_TAGS } = {}) {
  const wantTypes = new Set(types);
  const wantTags = new Set(tags);
  return documents
    .filter((doc) => doc.status === 'active' && doc.verified === true)
    .filter((doc) => wantTypes.has(doc.documentType) || (doc.tags || []).some((tag) => wantTags.has(tag)))
    .map((doc) => {
      const parsed = parseMirrorMarkdown(doc.markdown);
      const body = parsed ? recoverBody(parsed.body, doc.contentHash).body : '';
      return { id: doc.id, title: doc.title, documentType: doc.documentType, verifiedBy: doc.verifiedBy, body };
    })
    .sort((a, b) => (a.title < b.title ? -1 : a.title > b.title ? 1 : a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

// Any text shaped like a managed-block marker (this block's, or the skills'
// prax-memory pair that often shares the file) would make the file's markers
// ambiguous and every later edit refuse. Such text is rewritten as code.
export function neutraliseMarkers(text) {
  return String(text).replace(/<!--\s*([a-z][a-z0-9-]*):(start|end)\s*-->/gi, '`$1:$2 marker`');
}

const FENCE_RE = /^ {0,3}(`{3,}|~{3,})/;

// Body headings become bold lines so a document cannot restructure the host
// file; headings inside code fences are code and stay as they are.
function demoteHeadings(body) {
  let fence = null;
  return body.split('\n').map((line) => {
    const opener = FENCE_RE.exec(line);
    if (opener) {
      if (!fence) fence = opener[1][0];
      else if (opener[1][0] === fence) fence = null;
      return line;
    }
    if (fence) return line;
    const heading = /^ {0,3}#{1,6}\s+(.*?)\s*#*\s*$/.exec(line);
    return heading ? (heading[1] ? `**${heading[1]}**` : '') : line;
  }).join('\n');
}

// Cap one body at a line boundary, closing a code fence the cut left open.
function capBody(body, id, max) {
  if (body.length <= max) return body;
  const lines = body.split('\n');
  const kept = [];
  let size = 0;
  let fence = null;
  for (const line of lines) {
    if (size + line.length + 1 > max) break;
    kept.push(line);
    size += line.length + 1;
    const opener = FENCE_RE.exec(line);
    if (opener) {
      if (!fence) fence = opener[1];
      else if (opener[1][0] === fence[0]) fence = null;
    }
  }
  if (!kept.length) kept.push(`${lines[0].slice(0, max)}…`);
  if (fence) kept.push(fence);
  kept.push('', `_Truncated at ${max} characters; full text: \`prax get ${id}\`._`);
  return kept.join('\n');
}

function renderEntry(doc) {
  const body = capBody(demoteHeadings(doc.body.replace(/\r\n?/g, '\n').trim()), doc.id, DOCUMENT_BODY_MAX_CHARS);
  return neutraliseMarkers([
    `### ${doc.title}`,
    '',
    `_${doc.documentType} · ${doc.verifiedBy ? `verified by ${doc.verifiedBy}` : 'verified'} · \`prax get ${doc.id}\`_`,
    ...(body ? ['', body] : []),
    '',
  ].join('\n'));
}

function describeSelection(types, tags) {
  const parts = [];
  if (types.length) parts.push(`type ${types.join(' or ')}`);
  if (tags.length) parts.push(`tagged ${tags.join(' or ')}`);
  return parts.join(', or ') || 'no selection';
}

// The block's body (between the markers). Deterministic for equal inputs.
export function compileAgentsBlock({
  project, documents, types = DEFAULT_BLOCK_TYPES, tags = DEFAULT_BLOCK_TAGS, maxChars = DEFAULT_BLOCK_MAX_CHARS,
}) {
  const header = [
    `## Verified project knowledge: ${project} (compiled from Prax)`,
    '',
    `Generated by \`prax mirror --agents-block --project ${project}\` from verified, active Library`,
    `documents (${describeSelection(types, tags)}). Change the documents in Prax, not this block, then`,
    're-run the command. Unverified knowledge is never compiled here; find it with `prax recall`.',
    '',
    '',
  ].join('\n');
  if (!documents.length) {
    return neutraliseMarkers(`${header}_No verified documents match yet. Verify decisions in the Prax Library to compile them here._`);
  }
  const omittedNote = (n) => `_Not shown: ${n} more verified document${n === 1 ? '' : 's'} (block limit ${maxChars} characters). List every one with \`prax mirror --agents-block --print --project ${project} --max-chars <n>\` or \`prax context --project ${project}\`._`;
  const reserve = omittedNote(documents.length).length + 1;
  const entries = [];
  let used = header.length;
  for (let i = 0; i < documents.length; i += 1) {
    const entry = renderEntry(documents[i]);
    const last = i === documents.length - 1;
    const fits = used + entry.length + 1 <= maxChars;
    if (!fits || (!last && used + entry.length + 1 + reserve > maxChars)) break;
    entries.push(entry);
    used += entry.length + 1;
  }
  const omitted = documents.length - entries.length;
  const text = `${header}${entries.join('\n')}${omitted ? `${entries.length ? '\n' : ''}${omittedNote(omitted)}` : ''}`;
  return neutraliseMarkers(text.replace(/\n+$/, ''));
}

// The instruction file a repository's agents read: AGENTS.md, else CLAUDE.md
// (Claude Code reads it; in many checkouts it links to AGENTS.md), else a new
// AGENTS.md.
export function defaultInstructionFile(root) {
  for (const name of ['AGENTS.md', 'CLAUDE.md']) {
    if (existsSync(join(root, name))) return join(root, name);
  }
  return join(root, 'AGENTS.md');
}
