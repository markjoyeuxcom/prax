// `prax mirror`: a one-way, deterministic projection of one project's Library
// into a folder of the checkout, so knowledge changes show up as reviewable git
// diffs. SQLite stays the single source of truth; nothing here writes to Prax.
//
// The documents come rendered from the server's Markdown v3 exporter
// (GET /api/library/export?format=json&layout=mirror), so there is one format
// and one set of filename/link rules. This module decides which files to
// write, move and delete, and writes them atomically, skipping identical
// bytes. See docs/superpowers/specs/2026-09-23-library-git-mirror-design.md.
import {
  existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmdirSync, statSync, unlinkSync, writeFileSync,
} from 'node:fs';
import { randomUUID } from 'node:crypto';
import { dirname, join } from 'node:path';
import {
  isMirrorDocumentPath, MIRROR_FORMAT, MIRROR_INDEX, MIRROR_README, MIRROR_RETIRED, MIRROR_VERSION,
} from './mirrorFormat.js';

export class MirrorError extends Error {
  constructor(message) {
    super(message);
    this.name = 'MirrorError';
  }
}

// The server's JSON export, checked: an older server answers the same route
// with a ZIP, which must not be mistaken for an empty Library.
export async function fetchMirrorDocuments(client, project) {
  const response = await client.exportLibrary(project, { format: 'json', layout: 'mirror' });
  if (!response || typeof response !== 'object' || response.format !== 'prax.library-export'
      || response.layout !== 'mirror' || !Array.isArray(response.documents)) {
    throw new MirrorError('This Prax does not offer the mirror export (GET /api/library/export?format=json&layout=mirror); update the app.');
  }
  for (const doc of response.documents) {
    if (!isMirrorDocumentPath(doc?.path) || typeof doc.markdown !== 'string') {
      throw new MirrorError(`The export named an unexpected mirror path: ${JSON.stringify(doc?.path)}.`);
    }
  }
  return response.documents;
}

// The manifest the mirror owns its files by. No timestamps: the same Library
// state gives the same bytes.
export function renderMirrorIndex(project, documents) {
  const entries = [...documents]
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
    .map((doc) => ({
      path: doc.path,
      id: doc.id,
      title: doc.title,
      type: doc.documentType || 'note',
      status: doc.status || 'active',
      verified: Boolean(doc.verified),
      verifiedBy: doc.verifiedBy ?? null,
      contentHash: doc.contentHash ?? null,
    }));
  return `${JSON.stringify({ format: MIRROR_FORMAT, version: MIRROR_VERSION, project, documents: entries }, null, 2)}\n`;
}

function tableCell(value) {
  return String(value ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');
}

function linkTarget(path) {
  return path.split('/').map(encodeURIComponent).join('/');
}

export function renderMirrorReadme(project, documents) {
  const sorted = [...documents].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const table = (rows) => [
    '| Document | Type | Trust |',
    '| --- | --- | --- |',
    ...rows.map((doc) => `| [${tableCell(doc.title)}](${linkTarget(doc.path)}) | ${tableCell(doc.documentType || 'note')} | ${doc.verified ? (doc.verifiedBy ? `verified by ${tableCell(doc.verifiedBy)}` : 'verified') : 'unverified'} |`),
  ];
  const active = sorted.filter((doc) => !doc.path.startsWith(`${MIRROR_RETIRED}/`));
  const retired = sorted.filter((doc) => doc.path.startsWith(`${MIRROR_RETIRED}/`));
  const lines = [
    `# Prax Library mirror: ${project}`,
    '',
    `Generated by \`prax mirror --project ${project}\` from the project's Prax Library (Markdown v3).`,
    'Prax is the source of truth: do not edit these files here. Change the document in Prax and',
    're-run the command; the next mirror overwrites local edits. `index.json` is the manifest the',
    'mirror owns its files by. Receipts, revisions, run history, embeddings and archived documents',
    'are not mirrored.',
    '',
    `## Active (${active.length})`,
    '',
    ...(active.length ? table(active) : ['_None._']),
    '',
  ];
  if (retired.length) {
    lines.push(`## Retired (${retired.length})`, '', 'Superseded or deprecated; kept for history, not guidance.', '', ...table(retired), '');
  }
  return lines.join('\n');
}

// The folder's current state: the previous manifest (null when there is none
// or it is not a mirror manifest) and the `.md` files present.
export function readMirrorState(dir) {
  if (!existsSync(dir)) return { exists: false, empty: true, manifest: null, files: [] };
  if (!statSync(dir).isDirectory()) throw new MirrorError(`${dir} exists and is not a directory.`);
  const names = readdirSync(dir);
  let manifest = null;
  if (names.includes(MIRROR_INDEX)) {
    try {
      const parsed = JSON.parse(readFileSync(join(dir, MIRROR_INDEX), 'utf8'));
      if (parsed?.format === MIRROR_FORMAT && Array.isArray(parsed.documents)) manifest = parsed;
    } catch { /* not ours; handled as a folder without a manifest */ }
  }
  const files = names.filter((name) => /\.md$/i.test(name) && name !== MIRROR_README);
  const retiredDir = join(dir, MIRROR_RETIRED);
  if (existsSync(retiredDir) && statSync(retiredDir).isDirectory()) {
    for (const name of readdirSync(retiredDir)) if (/\.md$/i.test(name)) files.push(`${MIRROR_RETIRED}/${name}`);
  }
  const empty = names.filter((name) => name !== '.DS_Store').length === 0;
  return { exists: true, empty, manifest, files };
}

// What a mirror run changes. Pure: `state` from readMirrorState, `read` returns
// a file's current text or null.
export function planMirror({ project, documents, state, read }) {
  const desired = new Map(documents.map((doc) => [doc.path, doc.markdown]));
  const owned = new Set((state.manifest?.documents || []).map((entry) => entry?.path).filter(isMirrorDocumentPath));
  const previousPathById = new Map((state.manifest?.documents || [])
    .filter((entry) => isMirrorDocumentPath(entry?.path) && entry?.id).map((entry) => [entry.id, entry.path]));
  const plan = { added: [], updated: [], moved: [], deleted: [], unchanged: [], unmanaged: [], writes: [], deletes: [] };
  for (const doc of documents) {
    const current = read(doc.path);
    const previous = previousPathById.get(doc.id);
    if (current === doc.markdown) { plan.unchanged.push(doc.path); continue; }
    plan.writes.push(doc.path);
    if (previous && previous !== doc.path) plan.moved.push({ from: previous, to: doc.path });
    else if (current === null) plan.added.push(doc.path);
    else plan.updated.push(doc.path);
  }
  // `deleted` reports documents that left the mirror (archived, deleted, moved
  // to another project); `deletes` are the files to remove, which also covers
  // the old path of a moved document.
  const currentIds = new Set(documents.map((doc) => doc.id));
  for (const [id, path] of [...previousPathById].sort((a, b) => (a[1] < b[1] ? -1 : 1))) {
    if (!currentIds.has(id)) plan.deleted.push(path);
  }
  for (const path of [...owned].sort()) {
    if (!desired.has(path) && read(path) !== null) plan.deletes.push(path);
  }
  for (const path of [...state.files].sort()) {
    if (!desired.has(path) && !owned.has(path)) plan.unmanaged.push(path);
  }
  plan.readme = renderMirrorReadme(project, documents);
  plan.index = renderMirrorIndex(project, documents);
  plan.readmeChanged = read(MIRROR_README) !== plan.readme;
  plan.indexChanged = read(MIRROR_INDEX) !== plan.index;
  plan.stale = Boolean(plan.writes.length || plan.deletes.length || plan.readmeChanged || plan.indexChanged);
  // The interim manifest: every path this run may leave behind, so an
  // interrupted run is finished (and cleaned up) by the next one.
  const interim = new Map((state.manifest?.documents || []).filter((e) => isMirrorDocumentPath(e?.path)).map((e) => [e.path, e]));
  for (const doc of documents) interim.set(doc.path, { path: doc.path, id: doc.id });
  plan.interimIndex = `${JSON.stringify({ format: MIRROR_FORMAT, version: MIRROR_VERSION, project, documents: [...interim.values()], pending: true }, null, 2)}\n`;
  return plan;
}

function writeAtomic(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  const temporary = `${path}.prax-tmp.${randomUUID()}`;
  try {
    writeFileSync(temporary, text, { flag: 'wx' });
    renameSync(temporary, path);
  } finally {
    if (existsSync(temporary)) unlinkSync(temporary);
  }
}

function readText(path) {
  try { return readFileSync(path, 'utf8'); } catch { return null; }
}

// Write (or with `check`, only compare) the mirror. Returns the plan with
// `wrote: boolean`. Throws MirrorError for a folder it must not adopt.
export function writeMirror({ dir, project, documents, check = false, force = false }) {
  const state = readMirrorState(dir);
  if (state.exists && !state.empty && !state.manifest && !force) {
    throw new MirrorError(`${dir} is not empty and holds no mirror manifest (${MIRROR_INDEX}); pass --force to mirror into it anyway (files the mirror did not write are never deleted).`);
  }
  const plan = planMirror({ project, documents, state, read: (path) => readText(join(dir, path)) });
  if (check || !plan.stale) return { ...plan, wrote: false };
  mkdirSync(dir, { recursive: true });
  if (plan.writes.length || plan.deletes.length) writeAtomic(join(dir, MIRROR_INDEX), plan.interimIndex);
  const byPath = new Map(documents.map((doc) => [doc.path, doc.markdown]));
  for (const path of plan.writes) writeAtomic(join(dir, path), byPath.get(path));
  for (const path of plan.deletes) unlinkSync(join(dir, path));
  const retiredDir = join(dir, MIRROR_RETIRED);
  if (existsSync(retiredDir) && readdirSync(retiredDir).length === 0) rmdirSync(retiredDir);
  if (plan.readmeChanged) writeAtomic(join(dir, MIRROR_README), plan.readme);
  writeAtomic(join(dir, MIRROR_INDEX), plan.index);
  return { ...plan, wrote: true };
}

export function formatMirrorReport(result, { dir, check = false } = {}) {
  const count = (list, word) => `${list.length} ${word}`;
  const lines = [];
  const summary = [
    count(result.added, 'added'), count(result.updated, 'updated'), count(result.moved, 'moved'),
    count(result.deleted, 'deleted'), count(result.unchanged, 'unchanged'),
  ].join(', ');
  if (check) lines.push(result.stale ? `Mirror at ${dir} is stale: ${summary}.` : `Mirror at ${dir} is current (${result.unchanged.length} documents).`);
  else lines.push(result.wrote ? `Mirrored to ${dir}: ${summary}.` : `Mirror at ${dir} already current (${result.unchanged.length} documents).`);
  for (const path of result.added) lines.push(`  + ${path}`);
  for (const path of result.updated) lines.push(`  ~ ${path}`);
  for (const move of result.moved) lines.push(`  > ${move.from} -> ${move.to}`);
  for (const path of result.deleted) lines.push(`  - ${path}`);
  if (result.unmanaged.length) {
    lines.push(`Not managed by the mirror (left in place): ${result.unmanaged.join(', ')}.`);
  }
  return lines.join('\n');
}
