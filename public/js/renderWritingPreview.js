import { escapeHtml } from './html.js';
import { icon } from './icons.js';

// Preview overlay for an editor writing action (Tier-3 #7). The generated text is
// shown for review; the human clicks Apply to put it in the editor buffer (a
// user-assisted edit, not auto-saved) or Cancel. Pure state->HTML; the caller
// passes resultHtml (the generated Markdown already rendered, trusted).
export function renderWritingPreviewHtml(state, { resultHtml = '' } = {}) {
  const ctx = state.writeContext;
  if (!ctx) return '';
  let result;
  if (state.writeLoading) {
    result = '<div class="brief__status">Writing…</div>';
  } else if (state.writeError) {
    result = `<div class="brief__status brief__status--error" role="alert">${escapeHtml(state.writeError)}</div>`;
  } else if (state.writeResult) {
    // Honest about Apply: it is an edit that saves like typing, with Undo.
    const verified = ctx.verified
      ? ' This document is verified; applying keeps the mark, so read the result as carefully as a review.'
      : '';
    const model = `<div class="askprax__model">${ctx.model ? `Generated by ${escapeHtml(ctx.model)}. ` : ''}Nothing changes until you apply; applying saves like typing, and Undo restores the previous text.${escapeHtml(verified)}</div>`;
    result = `<div class="brief__result"><div class="prose">${resultHtml}</div>${model}</div>`;
  } else {
    result = '';
  }
  const canApply = Boolean(state.writeResult) && !state.writeLoading && !state.writeError;
  const failed = Boolean(state.writeError) && !state.writeLoading;
  // aria-modal: the workspace beneath (the editor included) goes inert while
  // the preview is open, so nothing typed can land in the document behind it.
  return `
    <div class="overlay-center" data-overlay="write" data-action="close-write">
      <div class="brief" role="dialog" aria-modal="true" aria-label="${escapeHtml(ctx.label || 'AI writing')}" aria-busy="${state.writeLoading ? 'true' : 'false'}" tabindex="-1">
        <div class="brief__row">
          ${icon('spark')}
          <span class="brief__title-text">${escapeHtml(ctx.label || 'AI')}</span>
        </div>
        ${result}
        <div class="brief__foot">
          <span class="brief__hint-k"><span class="kbd">Esc</span> cancel</span>
          <span class="brief__foot-actions">
            <button type="button" class="btn-ghost" data-action="close-write">${state.writeLoading ? 'Cancel' : 'Close'}</button>
            ${failed ? '<button type="button" class="btn-ghost" data-action="retry-write">Try again</button>' : ''}
            ${failed && /model/i.test(state.writeError) ? '<button type="button" class="btn-ghost" data-action="open-ai-settings">Settings ▸ Intelligence</button>' : ''}
            ${canApply ? `<button type="button" class="btn-ghost" data-action="copy-write">Copy</button>` : ''}
            ${canApply ? `<button type="button" class="btn-primary btn-primary--sm" data-action="apply-write">${escapeHtml(ctx.verb || 'Apply')}</button>` : ''}
          </span>
        </div>
      </div>
    </div>`;
}
